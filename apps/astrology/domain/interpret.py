def aspect_title(h: "Hit", a: str, b: str) -> str:
    return f"{SHORT[h.planet_a].capitalize()} {gen(a)} и {SHORT[h.planet_b]} {gen(b)} {TITLE_VERB[h.kind.key]}"


def overlay_title(o: "OverlayHit", owner: str, other: str) -> str:
    from .chart import HOUSE_AREA

    return f"{SHORT[o.planet].capitalize()} {gen(owner)} задевает у {gen(other)} сферу «{HOUSE_AREA[o.house]}»"


def aspect_line(h: "Hit") -> str:
    verb, _ = ASPECT[h.kind.key]
    return f"{PLANET[h.planet_a][0].capitalize()} одного и {PLANET[h.planet_b][0]} другого {verb}."


def aspect_text(h: "Hit", a: str, b: str) -> str:
    _, need_a, shadow_a = PLANET[h.planet_a]
    _, need_b, shadow_b = PLANET[h.planet_b]
    verb, dynamic = ASPECT[h.kind.key]
    text = (
        f"Здесь встречаются {SHORT[h.planet_a]} {gen(a)} и {SHORT[h.planet_b]} {gen(b)}. У вас они {verb}: {dynamic}. "
        f"Для {gen(a)} здесь главное — {need_a}, для {gen(b)} — {need_b}."
    )
    if h.tone == "attention":
        text += f" Под напряжением у {gen(a)} может проявиться {shadow_a}, у {gen(b)} — {shadow_b}."
    if h.double:
        text += " Связь работает в обе стороны — это один из самых сильных узлов вашей пары."
    return f"{text} {ADVICE[h.tone]}"


def overlay_text(o: "OverlayHit", owner: str, other: str) -> str:
    shadow = PLANET[o.planet][2]
    base = OVERLAY[o.house].format(owner=owner, other=other, other_gen=gen(other), other_dat=dat(other))
    tail = f" В трудный момент здесь может проявиться {shadow}." if o.effect < 0 else ""
    return f"{base[0].upper()}{base[1:]}{tail}"


def placement_text(name: str, point: str, sign: str, house: int | None, retro: bool, dignity: str | None) -> str:
    from .chart import HOUSE_AREA

    role, need, _ = PLANET[point]
    parts = [f"{point} в знаке {sign}: {role} у {gen(name)} проявляется {SIGN_STYLE[sign]}."]
    if house:
        parts.append(f"Дом {house} — «{HOUSE_AREA[house]}»: здесь {name} ищет {need}.")
    if dignity in ("обитель", "экзальтация"):
        parts.append(f"Планета в {dignity}: здесь ей легко, это сильная сторона.")
    elif dignity in ("изгнание", "падение"):
        parts.append(f"Планета в {dignity}: тема даётся через усилие и требует бережности.")
    if retro:
        parts.append("Ретроградность: тема прожита глубоко внутри и не всегда видна снаружи.")
    return " ".join(parts)


def composite_text(point: str, sign: str, house: int | None) -> str:
    role, _, _ = PLANET[point]
    text = f"{point} композита в знаке {sign}: {role} вашей пары проявляется {SIGN_STYLE[sign]}."
    if house:
        text += f" Дом {house}: {COMPOSITE_HOUSE[house]}."
    return text


